def render(title: str, sections, filename: str) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.add_font("hei", "", FONT)
    pdf.add_page()
    pdf.set_font("hei", "", 16)
    pdf.multi_cell(0, 10, title, align="C")
    pdf.ln(4)
    for head, paras in sections:
        pdf.set_font("hei", "", 13)
        pdf.multi_cell(0, 8, head)
        pdf.ln(1)
        pdf.set_font("hei", "", 11)
        for para in paras:
            pdf.multi_cell(0, 7, para)
            pdf.ln(1)
        pdf.ln(1)
    pdf.set_font("hei", "", 9)
    pdf.multi_cell(0, 6, "说明：本文档为演示样本，用于验证 PDF 解析与知识库接入，不代表任何机构的正式制度。")
    pdf.output(str(OUT / filename))
    print(f"[ok] {OUT / filename}")


